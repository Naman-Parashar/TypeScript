// ## `Omit<>` in TypeScript

// `Omit<T, K>` creates a new type by excluding specific properties from an existing type.

// - `T` = the original type
// - `K` = the property names to remove

// ### 1. Basic example

 
type Product = {
  id: number;
  name: string;
  price: number;
  stock: number;
};

type ProductWithoutStock = Omit<Product, "stock">;
 

// This is equivalent to:

 
type ProductWithoutStock2 = {
  id: number;
  name: string;
  price: number;
};
 

// Now `stock` is not part of the resulting type:

 
const product2: ProductWithoutStock2 = {
  id: 101,
  name: "Keyboard",
  price: 1500,
}; // Valid
 

// ### 2. Omit multiple properties

// Use a union (`|`) to specify more than one property:

 
type PublicProduct = Omit<Product, "stock" | "id">;
 

// This keeps only `name` and `price`.

// ### 3. React example: exclude fields from props

// Imagine a form component should receive product details, but the `id` is generated by the backend:

 
type Product3 = {
  id: number;
  name: string;
  price: number;
};

type CreateProductProps = Omit<Product, "id">;

// function CreateProductForm(props: CreateProductProps) {
//   // Form uses name and price
//   return <div>{props.name}: ₹{props.price}</div>;
// }
 

// The form’s props require `name` and `price`, but not `id`.

// ### `Pick` vs `Omit`

// | Utility                       | What it does                  |
// | ----------------------------- | ----------------------------- |
// | `Pick<T, "name" \\| "price">` | Keeps only `name` and `price` |
// | `Omit<T, "id">`               | Keeps everything except `id`  |

// Memory trick: `Pick` selects what you want; `Omit` removes what you don’t want.